#!/usr/bin/env python3
"""Phase 0 of `docs/RETICULEAN_PROPOSAL.md`: does the quartet certificate detect
recombination in a *program* population?

The proposal's central claim is that a candidate program's behavioural profile
over a probe battery is an aligned sequence -- four states plus a gap -- so the
Reticulata machinery applies unchanged. This script tests that claim on
synthetic profiles where the ground truth is known by construction, which is the
cheapest decisive experiment available and the one the proposal says to run
before adding any operator.

Two arms at matched budget:

* **clonal** -- variation is mutation from single parents, so the genealogy is a
  TREE by construction. This is the null arm.
* **recombinant** -- the same lineage plus crossovers, where a child takes a
  prefix from one parent and a suffix from another. That is a recombination
  breakpoint.

The mutation rate is swept, because this programme has learned twice over that a
statistic can be destroyed from both ends: too little variation and the null is
degenerate (no violating quadruple anywhere, so any positive observation is
"significant" -- LL.md G2), too much and saturation swamps the signal.

What this does and does not establish: it validates the *instrument* on profiles
whose truth is known. It says nothing yet about a real program population, whose
behavioural profiles are not generated by this model. Running it on
`alphaevolve_biomimetic` output is the next step, not this one.

    python scripts/reticulean_phase0_demo.py --out <dir>
"""

from __future__ import annotations

import argparse
import json
import random
import subprocess
from pathlib import Path
from typing import Dict, List, Tuple

# Correct / incorrect / raised / timed-out. `-` marks an inadmissible probe and
# is handled by the same complete deletion that handles a missing base.
SYMBOLS = "ACGT"
GAP = "-"


def mutate(profile: str, rate: float, rng: random.Random) -> str:
    out = list(profile)
    for index in range(len(out)):
        if rng.random() < rate:
            out[index] = rng.choice(SYMBOLS)
    return "".join(out)


def clonal_population(
    seed: int, probes: int, members: int, rate: float, generations: int
) -> Tuple[List[str], random.Random]:
    """A mutation-only lineage: a tree by construction, hence the null."""
    rng = random.Random(seed)
    population = ["".join(rng.choice(SYMBOLS) for _ in range(probes))]
    for _ in range(generations):
        population = [mutate(p, rate, rng) for p in population for _ in range(2)]
    return population[:members], rng


def recombinant_population(
    seed: int, probes: int, members: int, rate: float, generations: int, crossovers: int
) -> List[str]:
    """The same budget, plus crossovers at interior breakpoints."""
    population, rng = clonal_population(seed, probes, members, rate, generations)
    population = list(population)
    for _ in range(crossovers):
        left, right = rng.sample(range(len(population)), 2)
        cut = rng.randrange(probes // 4, 3 * probes // 4)
        population[left] = population[left][:cut] + population[right][cut:]
    return population


def write_profiles(path: Path, population: List[str], tag: str, inadmissible: int) -> None:
    rng = random.Random(99)
    records = []
    for index, profile in enumerate(population):
        symbols = list(profile)
        for _ in range(inadmissible):
            symbols[rng.randrange(len(symbols))] = GAP
        records.append(f">{tag}_{index:02d}\n" + "".join(symbols))
    path.write_text("\n".join(records) + "\n")


def run_profiles(binary: Path, fasta: Path) -> Dict[str, object]:
    done = subprocess.run(
        [str(binary), "profiles", str(fasta), "--top", "1"],
        capture_output=True,
        text=True,
        timeout=600,
    )
    if done.returncode != 0:
        raise RuntimeError(f"{fasta.name}: {done.stderr[:300]}")
    return json.loads(done.stdout)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument(
        "--binary",
        type=Path,
        default=Path("rust/reticulation/target/release/reticulation"),
    )
    parser.add_argument("--probes", type=int, default=1200)
    parser.add_argument("--members", type=int, default=8)
    parser.add_argument("--generations", type=int, default=3)
    parser.add_argument("--crossovers", type=int, default=3)
    parser.add_argument("--inadmissible", type=int, default=8)
    parser.add_argument("--seeds", type=int, default=3)
    parser.add_argument(
        "--rates",
        type=str,
        default="0.0005,0.002,0.008,0.02",
        help="mutation rates to sweep; the signal dies at both ends",
    )
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    rates = [float(r) for r in args.rates.split(",")]

    cells: List[Dict[str, object]] = []
    for rate in rates:
        tag = f"{rate:.4f}".replace(".", "p")
        arms: Dict[str, List[Dict[str, object]]] = {"clonal": [], "recombinant": []}
        for seed in range(1, args.seeds + 1):
            clonal, _ = clonal_population(
                seed, args.probes, args.members, rate, args.generations
            )
            recombinant = recombinant_population(
                seed, args.probes, args.members, rate, args.generations, args.crossovers
            )
            for name, population in (("clonal", clonal), ("recombinant", recombinant)):
                fasta = args.out / f"{name[:1]}_{tag}_s{seed}.fasta"
                write_profiles(fasta, population, name, args.inadmissible)
                report = run_profiles(args.binary, fasta)
                certificates = report["top_certificates"]
                margin = 0.0
                if certificates:
                    margin = (
                        certificates[0]["margin_num"] / certificates[0]["margin_den"]
                    )
                arms[name].append(
                    {
                        "seed": seed,
                        "violating_quadruples": report["violating_quadruples"],
                        "quadruples_examined": report["quadruples_examined"],
                        "max_margin": margin,
                        "revalidated": report["all_certificates_revalidated"],
                    }
                )

        clonal_margins = [float(r["max_margin"]) for r in arms["clonal"]]
        recomb_margins = [float(r["max_margin"]) for r in arms["recombinant"]]
        clonal_violating = [int(r["violating_quadruples"]) for r in arms["clonal"]]
        # The null must be able to vary, or nothing is measurable against it.
        null_varies = max(clonal_violating) > 0 and len(set(clonal_margins)) > 1
        cells.append(
            {
                "mutation_rate": rate,
                "clonal": arms["clonal"],
                "recombinant": arms["recombinant"],
                "max_clonal_margin": max(clonal_margins),
                "min_recombinant_margin": min(recomb_margins),
                "margin_separates": min(recomb_margins) > max(clonal_margins),
                "count_separates": min(
                    int(r["violating_quadruples"]) for r in arms["recombinant"]
                )
                > max(clonal_violating),
                "null_varies": null_varies,
                "interpretable": null_varies,
            }
        )

    usable = [c for c in cells if c["interpretable"] and c["margin_separates"]]
    report = {
        "experiment": "Phase 0 of the ReticuLean proposal: does the quartet certificate detect recombination in a program population?",
        "the_mapping": "A candidate's behavioural profile over a probe battery is a four-state sequence with a gap character, so a programs x probes matrix is an alignment and the Reticulata machinery applies unchanged.",
        "arms": {
            "clonal": "mutation from single parents; a tree by construction, hence the null",
            "recombinant": "the same budget plus crossovers at interior breakpoints",
        },
        "why_the_rate_is_swept": "The statistic dies at both ends. Too little variation and the null is degenerate -- no violating quadruple anywhere, so any positive observation is 'significant' (LL.md G2). Too much and saturation swamps the signal, which is how this programme's own topology line failed.",
        "scope": "Synthetic profiles with known ground truth. This validates the INSTRUMENT, not any claim about real program populations, whose profiles are not generated by this model.",
        "cells": cells,
        "summary": {
            "rates_tested": len(cells),
            "rates_with_a_non_degenerate_null": sum(1 for c in cells if c["null_varies"]),
            "rates_where_the_margin_separates_interpretably": len(usable),
            "rates_where_the_count_separates_interpretably": sum(
                1 for c in cells if c["interpretable"] and c["count_separates"]
            ),
        },
    }
    out = args.out / "phase0.json"
    out.write_text(json.dumps(report, indent=2) + "\n")

    header = "{:>8} {:>14} {:>14} {:>13} {:>13} {:>8} {:>8} {:>7}"
    print(header.format("rate", "clonal viol", "recomb viol", "max clon mg",
                        "min rec mg", "mg sep", "cnt sep", "usable"))
    for cell in cells:
        print(header.format(
            "{:.4f}".format(cell["mutation_rate"]),
            str([r["violating_quadruples"] for r in cell["clonal"]]),
            str([r["violating_quadruples"] for r in cell["recombinant"]]),
            "{:.5f}".format(cell["max_clonal_margin"]),
            "{:.5f}".format(cell["min_recombinant_margin"]),
            str(cell["margin_separates"]),
            str(cell["count_separates"]),
            str(cell["interpretable"]),
        ))
    print(f"\nwrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
