#!/usr/bin/env python3
"""Does a quartet certificate detect recombination in a REAL program population?

`reticulean_phase0_demo.py` validated the instrument on synthetic profiles whose
genealogy held by construction. The profiles there were generated by a
hand-written mutation model, so the only thing it could establish was that the
machinery runs. This runs the same question on programs that are actually
built, actually executed, and actually measured.

PROGRAM REPRESENTATION. Expression trees over a closed grammar: terminals `x`
and small integer constants, operators `+`, `-`, `*` and a protected division.
The grammar is closed deliberately -- it cannot express an import, an attribute
access or a call -- so evolved individuals are safe to evaluate directly and no
sandbox is load-bearing. This is classical genetic programming, which is also
the setting in which crossover's contribution has been argued about for thirty
years.

BEHAVIOURAL PROFILE. Each individual is evaluated at every probe point and the
outcome recorded as one symbol, giving the four-state alphabet plus gap that
`subset::Alignment` already assumes:

    A  within tolerance of the target
    C  finite but outside tolerance
    G  raised (the protected division still lets overflow through)
    T  returned a non-finite value
    -  probe inadmissible for this individual

TWO ARMS AT MATCHED BUDGET. The clonal arm applies only point mutations, so
every individual descends from a single parent and the genealogy is a TREE by
construction: this is the null, and it is the right null rather than a
convenient one. The recombinant arm spends the same number of variation events
but routes some of them through subtree exchange, which is a recombination with
a breakpoint. Matching the event count is what makes the comparison fair.

WHAT IS PRE-REGISTERED (before any run, per LL.md G1/G8):

    P1  the clonal null is non-degenerate: it produces violating quadruples, so
        something can be measured against it (G2)
    P2  the floor converges: drawing 25 clonal populations instead of 5 stops
        raising the running maximum (G4)
    P3  the recombinant arm's margin exceeds the clonal floor, decided on the
        integer count first and only then as a rate (G6)
    P4  the effect is not an artifact of final fitness: it survives restricting
        both arms to populations of comparable best-fitness

P4 is the one that can embarrass this. If recombination merely reaches better
programs, and better programs happen to have more varied profiles, then the
certificate is detecting fitness and not recombination at all.

    python scripts/reticulean_gp_experiment.py --out data/reticulean_gp
"""

from __future__ import annotations

import argparse
import json
import math
import random
import statistics
import subprocess
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Dict, List, Optional, Sequence, Tuple

TOLERANCE = 0.01
PROBE_LOW, PROBE_HIGH = -2.0, 2.0


# ---------------------------------------------------------------- the grammar

@dataclass(frozen=True)
class Node:
    """An expression tree node. `op` is a terminal name or an operator symbol."""

    op: str
    children: Tuple["Node", ...] = ()

    def size(self) -> int:
        return 1 + sum(c.size() for c in self.children)


OPERATORS: Tuple[str, ...] = ("+", "-", "*", "/")
CONSTANTS: Tuple[int, ...] = (-3, -2, -1, 1, 2, 3)


def random_tree(rng: random.Random, depth: int) -> Node:
    if depth <= 1 or rng.random() < 0.3:
        if rng.random() < 0.5:
            return Node("x")
        return Node(str(rng.choice(CONSTANTS)))
    op = rng.choice(OPERATORS)
    return Node(op, (random_tree(rng, depth - 1), random_tree(rng, depth - 1)))


def evaluate(node: Node, x: float) -> float:
    """Evaluate the tree. Protected division raises on a zero denominator rather
    than silently returning a constant, because a silent fallback would turn a
    structural failure into an ordinary wrong answer and erase a profile state."""
    if node.op == "x":
        return x
    if not node.children:
        return float(node.op)
    left = evaluate(node.children[0], x)
    right = evaluate(node.children[1], x)
    if node.op == "+":
        return left + right
    if node.op == "-":
        return left - right
    if node.op == "*":
        return left * right
    if abs(right) < 1e-12:
        raise ZeroDivisionError("protected division guard")
    return left / right


def render(node: Node) -> str:
    if not node.children:
        return node.op
    return f"({render(node.children[0])} {node.op} {render(node.children[1])})"


# ------------------------------------------------------- variation operators

def nodes_of(node: Node, path: Tuple[int, ...] = ()) -> List[Tuple[Tuple[int, ...], Node]]:
    out = [(path, node)]
    for index, child in enumerate(node.children):
        out.extend(nodes_of(child, path + (index,)))
    return out


def replace_at(node: Node, path: Sequence[int], replacement: Node) -> Node:
    if not path:
        return replacement
    index = path[0]
    children = list(node.children)
    children[index] = replace_at(children[index], path[1:], replacement)
    return Node(node.op, tuple(children))


def point_mutate(node: Node, rng: random.Random) -> Node:
    """Change one node in place: an operator for another, or a terminal for
    another. Structure is preserved, so this is a point mutation rather than a
    structural one -- which keeps the clonal arm's lineage a clean tree."""
    candidates = nodes_of(node)
    path, target = rng.choice(candidates)
    if target.children:
        new_op = rng.choice([o for o in OPERATORS if o != target.op])
        replacement = Node(new_op, target.children)
    elif target.op == "x":
        replacement = Node(str(rng.choice(CONSTANTS)))
    else:
        replacement = Node("x") if rng.random() < 0.5 else Node(str(rng.choice(CONSTANTS)))
    return replace_at(node, path, replacement)


def subtree_crossover(a: Node, b: Node, rng: random.Random, max_size: int) -> Node:
    """Exchange a subtree of `a` for a subtree of `b`: a recombination with a
    breakpoint. Size is capped so the arms stay comparable in program size and
    the comparison is not confounded by bloat."""
    for _ in range(12):
        path_a, _ = rng.choice(nodes_of(a))
        _, donor = rng.choice(nodes_of(b))
        child = replace_at(a, path_a, donor)
        if child.size() <= max_size:
            return child
    return a


# ----------------------------------------------------------------- behaviour

def target_function(x: float) -> float:
    """A rational target, so division is genuinely required and the `G` state is
    reachable by structurally wrong programs."""
    return (x * x * x - 2.0 * x + 1.0) / (x * x + 1.0)


def profile_and_fitness(
    node: Node, probes: Sequence[float]
) -> Tuple[str, float]:
    """One symbol per probe, plus mean absolute error over the finite ones."""
    symbols: List[str] = []
    errors: List[float] = []
    for x in probes:
        try:
            value = evaluate(node, x)
        except (ZeroDivisionError, OverflowError, ValueError):
            symbols.append("G")
            continue
        if not math.isfinite(value):
            symbols.append("T")
            continue
        error = abs(value - target_function(x))
        errors.append(error)
        symbols.append("A" if error <= TOLERANCE else "C")
    fitness = statistics.fmean(errors) if errors else float("inf")
    return "".join(symbols), fitness


# ------------------------------------------------------------------ the runs

def evolve(
    seed: int,
    probes: Sequence[float],
    members: int,
    generations: int,
    events: int,
    crossover_share: float,
    max_size: int,
) -> List[Node]:
    """Tournament evolution with a fixed VARIATION EVENT budget.

    `crossover_share` routes that fraction of events through subtree exchange.
    At zero the arm is clonal: every individual descends from one parent, so the
    genealogy is a tree.
    """
    rng = random.Random(seed)
    population = [random_tree(rng, 4) for _ in range(members)]
    for _ in range(generations):
        scored = sorted(
            population, key=lambda n: profile_and_fitness(n, probes)[1]
        )
        survivors = scored[: max(2, members // 2)]
        children: List[Node] = list(survivors)
        while len(children) < members:
            parent = rng.choice(survivors)
            if rng.random() < crossover_share and len(survivors) > 1:
                other = rng.choice([s for s in survivors if s is not parent])
                child = subtree_crossover(parent, other, rng, max_size)
            else:
                child = parent
            for _ in range(max(1, events // members)):
                child = point_mutate(child, rng)
            children.append(child)
        population = children
    return population


def behavioural_spread(profiles: Sequence[str]) -> float:
    """Mean pairwise Hamming distance between behavioural profiles.

    This is the nuisance the certificate actually depends on, and it is NOT the
    variation-event budget. Matching the budget and assuming the divergence
    follows is the same error as matching a null in expectation (LL.md G3): the
    first run of this experiment matched events exactly and the recombinant arm
    came out 6.5x tighter in realised spread, which is why its margins vanished.
    """
    pairs = [
        sum(1 for a, b in zip(profiles[i], profiles[j]) if a != b) / max(1, len(profiles[i]))
        for i in range(len(profiles))
        for j in range(i + 1, len(profiles))
    ]
    return statistics.fmean(pairs) if pairs else 0.0


def write_profiles(path: Path, population: Sequence[Node], probes: Sequence[float], tag: str) -> Dict[str, object]:
    records = []
    fitnesses = []
    raw_profiles = []
    for index, node in enumerate(population):
        profile, fitness = profile_and_fitness(node, probes)
        records.append(f">{tag}_{index:02d}\n{profile}")
        raw_profiles.append(profile)
        fitnesses.append(fitness)
    path.write_text("\n".join(records) + "\n")
    finite = [f for f in fitnesses if math.isfinite(f)]
    best_index = min(range(len(fitnesses)), key=lambda i: fitnesses[i])
    return {
        "members": len(population),
        "best_fitness": min(finite) if finite else None,
        "mean_size": statistics.fmean(n.size() for n in population),
        "best_program": render(population[best_index]),
        "behavioural_spread": behavioural_spread(raw_profiles),
        "distinct_profiles": len(set(raw_profiles)),
    }


def certify(binary: Path, fasta: Path) -> Dict[str, object]:
    done = subprocess.run(
        [str(binary), "profiles", str(fasta), "--top", "1"],
        capture_output=True,
        text=True,
        timeout=900,
    )
    if done.returncode != 0:
        raise RuntimeError(f"{fasta.name}: {done.stderr[:300]}")
    report = json.loads(done.stdout)
    certificates = report["top_certificates"]
    margin_num = certificates[0]["margin_num"] if certificates else 0
    margin_den = certificates[0]["margin_den"] if certificates else 1
    return {
        "violating_quadruples": report["violating_quadruples"],
        "quadruples_examined": report["quadruples_examined"],
        "margin_num": margin_num,
        "margin_den": margin_den,
        "margin_rate": margin_num / margin_den if margin_den else 0.0,
        "revalidated": report["all_certificates_revalidated"],
        "sites": report["sites"],
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument(
        "--binary", type=Path,
        default=Path("rust/reticulation/target/release/reticulation"),
    )
    parser.add_argument("--probes", type=int, default=600)
    parser.add_argument("--members", type=int, default=8)
    parser.add_argument("--generations", type=int, default=12)
    parser.add_argument("--events", type=int, default=16)
    parser.add_argument("--max-size", type=int, default=40)
    parser.add_argument("--crossover-shares", type=str, default="0.1,0.2,0.4,0.6",
                        help="swept, because realised behavioural spread does not "
                             "follow the variation-event budget")
    parser.add_argument("--null-runs", type=int, default=25,
                        help="clonal populations; the floor uses the first 5 and "
                             "the rest measure whether it converged")
    parser.add_argument("--floor-runs", type=int, default=5)
    parser.add_argument("--test-runs", type=int, default=10)
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)

    rng = random.Random(20261024)
    probes = [rng.uniform(PROBE_LOW, PROBE_HIGH) for _ in range(args.probes)]

    def run_arm(name: str, seeds: Sequence[int], share: float) -> List[Dict[str, object]]:
        rows = []
        for seed in seeds:
            population = evolve(
                seed, probes, args.members, args.generations, args.events,
                share, args.max_size,
            )
            fasta = args.out / f"{name}_s{seed}.fasta"
            meta = write_profiles(fasta, population, probes, name)
            cert = certify(args.binary, fasta)
            rows.append({"seed": seed, **meta, **cert})
        return rows

    clonal = run_arm("clonal", range(1, args.null_runs + 1), 0.0)
    # Sweep the crossover share. The first run of this experiment used a single
    # share of 0.6 and the recombinant arm's realised behavioural spread came
    # out 6.5x TIGHTER than the clonal arm's, so the two were never comparable
    # and the margin comparison was meaningless. Sweeping gives runs at a range
    # of realised spreads, from which comparable ones can be selected.
    recombinant: List[Dict[str, object]] = []
    for share in [float(s) for s in args.crossover_shares.split(",")]:
        tag = f"recomb{int(share * 100):02d}"
        base = 1000 + int(share * 100) * 100
        for row in run_arm(tag, range(base, base + args.test_runs), share):
            row["crossover_share"] = share
            recombinant.append(row)

    # --- the floor, and whether it converged (G4) ---
    running: List[float] = []
    best = 0.0
    for row in clonal:
        best = max(best, float(row["margin_rate"]))
        running.append(best)
    floor_published = running[args.floor_runs - 1]
    floor_extended = running[-1]
    # The integer count behind the published floor, for the G6 comparison.
    floor_num = max(
        int(r["margin_num"]) for r in clonal[: args.floor_runs]
    )

    clonal_violating = [int(r["violating_quadruples"]) for r in clonal]
    null_degenerate = max(clonal_violating) == 0

    def verdict(row: Dict[str, object]) -> str:
        num = int(row["margin_num"])
        if num < floor_num:
            return "below the floor"
        if num == floor_num:
            return "UNRESOLVED: same margin count as the floor"
        if float(row["margin_rate"]) <= floor_extended:
            return "UNRESOLVED: clears the five-run floor but not the converged floor"
        return "above the converged floor"

    for row in recombinant:
        row["verdict"] = verdict(row)
        row["resolved_above"] = row["verdict"] == "above the converged floor"

    # --- P5: compare only at MATCHED REALISED SPREAD (G3) ---
    #
    # The nuisance is behavioural spread, not the event budget. A recombinant
    # run counts only if its realised spread lies inside the clonal arm's
    # observed range; otherwise the two populations are not comparable and no
    # verdict is reported for that pair rather than a verdict from an unmatched
    # null.
    clonal_spreads = [float(r["behavioural_spread"]) for r in clonal]
    spread_low, spread_high = min(clonal_spreads), max(clonal_spreads)
    spread_matched = [
        r for r in recombinant
        if spread_low <= float(r["behavioural_spread"]) <= spread_high
    ]
    spread_matched_above = [
        r for r in spread_matched if int(r["margin_num"]) > floor_num
    ]

    # --- P4: is it fitness rather than recombination? ---
    clonal_best = [float(r["best_fitness"]) for r in clonal if r["best_fitness"] is not None]
    recomb_best = [float(r["best_fitness"]) for r in recombinant if r["best_fitness"] is not None]
    overlap_low = max(min(clonal_best), min(recomb_best))
    overlap_high = min(max(clonal_best), max(recomb_best))
    matched_clonal = [r for r in clonal if r["best_fitness"] is not None
                      and overlap_low <= float(r["best_fitness"]) <= overlap_high]
    matched_recomb = [r for r in recombinant if r["best_fitness"] is not None
                      and overlap_low <= float(r["best_fitness"]) <= overlap_high]
    matched_floor_num = max((int(r["margin_num"]) for r in matched_clonal), default=0)
    matched_above = [r for r in matched_recomb if int(r["margin_num"]) > matched_floor_num]

    report = {
        "experiment": "does a quartet certificate detect recombination in a real program population?",
        "representation": "expression trees over a closed grammar (x, small integer constants, + - * protected /); the grammar cannot express an import, attribute access or call, so evolved individuals are safe to evaluate and no sandbox is load-bearing",
        "target": "(x^3 - 2x + 1) / (x^2 + 1)",
        "profile_alphabet": {"A": "within tolerance", "C": "finite but outside tolerance",
                             "G": "raised", "T": "non-finite", "-": "inadmissible probe"},
        "arms": {
            "clonal": "point mutation only; every individual descends from one parent, so the genealogy is a TREE by construction -- the null",
            "recombinant": f"the same variation-event budget, with crossover shares {args.crossover_shares} of events routed through subtree exchange (a breakpoint)",
            "budget_matching": "both arms spend the same number of variation events per generation; size is capped so bloat cannot confound",
        },
        "design": {
            "probes": args.probes, "members": args.members,
            "generations": args.generations, "events_per_generation": args.events,
            "max_program_size": args.max_size,
            "null_runs": args.null_runs, "floor_runs": args.floor_runs,
            "test_runs": args.test_runs,
        },
        "preregistered": {
            "P5_matched_on_realised_spread": {
                "why": "The certificate depends on behavioural spread, not on the variation-event budget. Matching the budget and assuming the spread follows is the error LL.md G3 names: the first run matched events exactly and the recombinant arm came out 6.5x tighter, so the arms were never comparable.",
                "clonal_spread_range": [spread_low, spread_high],
                "recombinant_runs_total": len(recombinant),
                "recombinant_runs_inside_the_clonal_spread_range": len(spread_matched),
                "held": len(spread_matched_above),
                "of": len(spread_matched),
                "claim": "among recombinant runs whose realised spread matches the clonal arm's, the margin exceeds the clonal floor",
            },
            "P1_null_is_non_degenerate": {
                "held": not null_degenerate,
                "clonal_violating_quadruples": clonal_violating,
                "claim": "the clonal null produces violating quadruples, so something can be measured against it",
            },
            "P2_floor_converged": {
                "floor_at_5_runs": floor_published,
                "floor_at_all_runs": floor_extended,
                "growth_factor": (floor_extended / floor_published) if floor_published else None,
                "held": floor_published > 0 and floor_extended <= floor_published * 1.0001,
                "claim": "drawing more clonal runs stops raising the running maximum",
            },
            "P3_recombinant_exceeds_the_floor": {
                "held": sum(1 for r in recombinant if r["resolved_above"]),
                "of": len(recombinant),
                "floor_margin_count": floor_num,
                "claim": "decided on the integer margin count first, then the rate against the converged floor",
            },
            "P4_not_an_artifact_of_fitness": {
                "fitness_overlap_window": [overlap_low, overlap_high],
                "matched_clonal_runs": len(matched_clonal),
                "matched_recombinant_runs": len(matched_recomb),
                "matched_floor_margin_count": matched_floor_num,
                "held": len(matched_above),
                "of": len(matched_recomb),
                "claim": "restricted to runs of comparable best fitness, the recombinant arm still exceeds the clonal floor; if this fails the certificate is detecting fitness, not recombination",
            },
        },
        "fitness": {
            "clonal_best": clonal_best,
            "recombinant_best": recomb_best,
            "clonal_median": statistics.median(clonal_best) if clonal_best else None,
            "recombinant_median": statistics.median(recomb_best) if recomb_best else None,
        },
        "floor_running_maximum": running,
        "clonal": clonal,
        "recombinant": recombinant,
    }
    out = args.out / "gp_experiment.json"
    out.write_text(json.dumps(report, indent=2) + "\n")

    print(f"clonal violating quadruples : {clonal_violating}")
    print(f"null degenerate             : {null_degenerate}")
    print(f"floor at {args.floor_runs} runs  : {floor_published:.6f} (count {floor_num})")
    print(f"floor at {len(clonal)} runs : {floor_extended:.6f}  growth "
          f"{(floor_extended / floor_published) if floor_published else float('nan'):.2f}x")
    print()
    for row in recombinant:
        print(f"  recomb s{row['seed']}: margin {row['margin_num']}/{row['margin_den']} "
              f"viol {row['violating_quadruples']:>3} best_fit "
              f"{row['best_fitness']:.4f} -> {row['verdict']}")
    print()
    p3 = report["preregistered"]["P3_recombinant_exceeds_the_floor"]
    p4 = report["preregistered"]["P4_not_an_artifact_of_fitness"]
    print(f"P1 null non-degenerate : {report['preregistered']['P1_null_is_non_degenerate']['held']}")
    print(f"P2 floor converged     : {report['preregistered']['P2_floor_converged']['held']}")
    print(f"P3 above floor         : {p3['held']}/{p3['of']}")
    p5 = report["preregistered"]["P5_matched_on_realised_spread"]
    print(f"P4 fitness-matched     : {p4['held']}/{p4['of']}")
    print(f"P5 spread-matched      : {p5['held']}/{p5['of']} "
          f"(of {p5['recombinant_runs_total']} recombinant runs, "
          f"{p5['recombinant_runs_inside_the_clonal_spread_range']} were comparable)")
    print()
    print(f"{'share':>6} {'spread':>9} {'distinct':>9} {'viol':>5} {'margin':>10} {'best_fit':>9}")
    for row in recombinant:
        print(f"{row['crossover_share']:>6.1f} {row['behavioural_spread']:>9.4f} "
              f"{row['distinct_profiles']:>9} {row['violating_quadruples']:>5} "
              f"{str(row['margin_num']) + '/' + str(row['margin_den']):>10} "
              f"{row['best_fitness']:>9.4f}")
    print(f"\nclonal spread range   : {spread_low:.4f} .. {spread_high:.4f}")
    print(f"\nwrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
