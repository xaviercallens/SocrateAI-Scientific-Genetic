def token() -> str:
    spec = importlib.util.spec_from_file_location("p", REPO / "scripts/three_breakthroughs/publish_3breakthroughs_to_zenodo.py")
    mod = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(mod)
    return str(mod.load_zenodo_token())


def req(method: str, url: str, tok: str, data: bytes | None = None, ctype: str = "application/json") -> dict[str, Any]:
    r = urllib.request.Request(url, data=data, method=method, headers={"Authorization": f"Bearer {tok}", "Content-Type": ctype})
    with urllib.request.urlopen(r, timeout=600) as resp:
        body = resp.read()
        return json.loads(body) if body else {}


def bundle(p: dict[str, Any]) -> list[Path]:
    files = [HERE / "papers" / f"{p['stem']}.pdf", HERE / "papers" / f"{p['stem']}.tex"]
    files += [HERE / "papers" / f for f in p["figs"]]
    files += [HERE / "data" / f for f in p["data"]]
    files += [HERE / "formal" / "ANSE" / f for f in p["lean"]]
    files += COMMON
    missing = [str(f) for f in files if not f.exists()]
    assert not missing, missing
    return files


def main() -> int:
    tok = token()
    receipts = []
    for p in PAPERS:
        prev = req("GET", f"{ZENODO}/deposit/depositions/{p['prev']}", tok)
        assert prev["state"] == "done", prev["state"]
        nv = req("POST", f"{ZENODO}/deposit/depositions/{p['prev']}/actions/newversion", tok)
        dep = req("GET", nv["links"]["latest_draft"], tok)
        for old in dep.get("files", []):
            req("DELETE", f"{ZENODO}/deposit/depositions/{dep['id']}/files/{old['id']}", tok)
        sums = {}
        for f in bundle(p):
            req("PUT", f"{dep['links']['bucket']}/{f.name}", tok, f.read_bytes(), "application/octet-stream")
            sums[f.name] = hashlib.sha256(f.read_bytes()).hexdigest()
        meta = {"metadata": {
            "title": p["title"], "upload_type": "publication", "publication_type": "preprint",
            "description": p["description"], "creators": [{"name": "Callens, Xavier", "affiliation": "SocrateAI Lab"}],
            "keywords": p["keywords"], "license": "cc-by-4.0", "version": "2",
            "related_identifiers": [
                {"identifier": "https://github.com/xaviercallens/SocrateAI-Scientific-Genetic", "relation": "isSupplementTo", "scheme": "url"},
                {"identifier": f"10.5281/zenodo.{p['prev']}", "relation": "isNewVersionOf", "scheme": "doi"}],
        }}
        req("PUT", f"{ZENODO}/deposit/depositions/{dep['id']}", tok, json.dumps(meta).encode())
        done = req("POST", f"{ZENODO}/deposit/depositions/{dep['id']}/actions/publish", tok)
        receipts.append({"previous": p["prev"], "id": done.get("id"), "doi": done.get("doi"), "state": done.get("state"),
                         "conceptrecid": done.get("conceptrecid"), "sha256": sums})
        print(receipts[-1]["id"], receipts[-1]["doi"], receipts[-1]["state"])
    RECEIPT.write_text(json.dumps(receipts, indent=2) + "\n", encoding="utf-8")
    return 0


